CREATE DATABASE IF NOT EXISTS frio CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE frio;

CREATE TABLE IF NOT EXISTS lecturas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    fecha DATETIME DEFAULT CURRENT_TIMESTAMP,
    temperatura FLOAT,
    puerta TINYINT,
    bateria TINYINT,
    estado VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS eventos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    fecha DATETIME DEFAULT CURRENT_TIMESTAMP,
    tipo VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS comandos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    fecha DATETIME DEFAULT CURRENT_TIMESTAMP,
    accion VARCHAR(20),
    origen VARCHAR(20),
    resultado VARCHAR(20)
);
